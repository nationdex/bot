export function applyPresetToPrefs(prefs: ThemePrefs, preset: ThemePreset): ThemePrefs {
  return {
    ...prefs,
    dark: { ...preset.dark },
    light: { ...preset.light },
  };
}

export function presetShellBackground(palette: ThemePalette): string {
  return palette.gradientEnabled
    ? `linear-gradient(${palette.gradientAngle}deg, ${palette.gradientFrom}, ${palette.gradientTo})`
    : palette.shell;
}
